"""Enable the built-in RAG module in an existing Minix project."""

from __future__ import annotations

import ast
import os
import re
from pathlib import Path

import typer
from dotenv import dotenv_values

from minix.core.cli.commands.init_scaffold import minix_pip_install_spec

_AUTH = "minix.core.modules.auth.AuthModule"
_RAG = "minix.core.modules.rag.RagModule"
_TEMPLATES = Path(__file__).resolve().parents[2] / "conf" / "project_template"
_DOCKER_MARKER = "# Minix RAG dependencies"
_COMPOSE_MARKER = "# Generated by minix add rag."


def _setting(tree: ast.Module, name: str) -> ast.expr | None:
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.target.id.lower() == name:
                return node.value
        if isinstance(node, ast.Assign):
            if any(isinstance(t, ast.Name) and t.id.lower() == name for t in node.targets):
                return node.value
    return None


def _default(value: ast.expr | None) -> ast.expr | None:
    """Unwrap a settings Field without importing or executing project code."""
    if isinstance(value, ast.Call):
        for kw in value.keywords:
            if kw.arg == "default_factory" and isinstance(kw.value, ast.Lambda):
                return kw.value.body
            if kw.arg == "default":
                return kw.value
    return value


def _dict_value(value: ast.expr | None, key: str) -> ast.expr | None:
    if isinstance(value, ast.Dict):
        for k, v in zip(value.keys, value.values):
            if isinstance(k, ast.Constant) and k.value == key:
                return v
    return None


def _postgresql_default(tree: ast.Module, env: dict) -> bool:
    database = _dict_value(_default(_setting(tree, "databases")), "default")
    value = _dict_value(database, "driver")
    driver = None
    if isinstance(value, ast.Call) and value.args:
        # Respect the actual environment key used by the connection.
        key = value.args[0]
        if isinstance(key, ast.Constant) and isinstance(key.value, str):
            driver = os.environ.get(key.value) or env.get(key.value)
        value = value.args[1] if len(value.args) >= 2 else None
    if driver is None and isinstance(value, ast.Constant):
        driver = value.value
    return isinstance(driver, str) and driver.lower() in {"postgresql", "postgres", "pgsql"}


def _register_modules(source: str, tree: ast.Module) -> str:
    value = _default(_setting(tree, "installed_modules"))
    if not isinstance(value, ast.List) or not all(
        isinstance(item, ast.Constant) and isinstance(item.value, str) for item in value.elts
    ):
        raise ValueError("installed_modules must be a literal list or Field(default_factory=lambda: [...]).")
    existing = {item.value for item in value.elts}
    missing = [path for path in (_AUTH, _RAG) if path not in existing]
    if not missing:
        return source

    # AST columns are UTF-8 byte offsets. Insert into the existing list while
    # preserving comments, formatting, and all unrelated project settings.
    data = source.encode("utf-8")
    lines = data.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    close = offsets[value.end_lineno - 1] + value.end_col_offset - 1
    close_line = lines[value.end_lineno - 1]
    indent = close_line[:len(close_line) - len(close_line.lstrip())].decode("utf-8")
    entries = "\n" + "".join(f'{indent}    "{path}",\n' for path in missing) + indent
    edits = [(close, entries.encode("utf-8"))]
    if value.elts:
        last = value.elts[-1]
        end = offsets[last.end_lineno - 1] + last.end_col_offset
        # Ignore comments when looking for an existing trailing comma.
        tail = re.sub(rb"#[^\n]*", b"", data[end:close]).strip()
        if not tail.startswith(b","):
            edits.append((end, b","))
    for pos, addition in sorted(edits, reverse=True):
        data = data[:pos] + addition + data[pos:]
    result = data.decode("utf-8")
    ast.parse(result)
    return result


def _env_content(source: str, defaults: str) -> str:
    from io import StringIO

    existing = dotenv_values(stream=StringIO(source), interpolate=False)
    additions = []
    for line in defaults.splitlines():
        if not line or line.startswith("#") or line.split("=", 1)[0] not in existing:
            additions.append(line)
    if not any(line and not line.startswith("#") for line in additions):
        return source
    return source.rstrip("\n") + "\n\n" + "\n".join(additions).strip() + "\n"


def _compose_override(base: str) -> str:
    result = _COMPOSE_MARKER + "\nservices:\n"
    for service in ("app", "celery_worker", "celery_beat"):
        if re.search(rf"^  {service}:\s*$", base, re.MULTILINE):
            result += (
                f"  {service}:\n"
                "    environment:\n"
                "      QDRANT_URL: http://qdrant:6333\n"
                "    depends_on:\n"
                "      - qdrant\n"
            )
    if not re.search(r"^  qdrant:\s*$", base, re.MULTILINE):
        result += """  qdrant:
    image: qdrant/qdrant
    ports:
      - "${QDRANT_PORT:-6333}:6333"
      - "${QDRANT_GRPC_PORT:-6334}:6334"
    environment:
      QDRANT__SERVICE__API_KEY: ${QDRANT_API_KEY:-}
    volumes:
      - rag-qdrant-data:/qdrant/storage
    networks:
      - backend
volumes:
  rag-qdrant-data:
"""
    return result


def rag():
    """Enable RAG in the current project; retain existing settings and secrets.

    Requires PostgreSQL as the default database. Adds module registration,
    missing environment settings, Docker dependencies, and a Compose override.
    """
    root = Path.cwd()
    config_path = root / "config.py"
    if not config_path.is_file():
        typer.echo("No config.py found. Run this command in a Minix project, or use minix init APP_NAME --rag.", err=True)
        raise typer.Exit(code=1)

    try:
        source = config_path.read_text()
        tree = ast.parse(source)
        env = dotenv_values(root / ".env")
        if not _postgresql_default(tree, env):
            raise ValueError(
                "RAG requires PostgreSQL as the default database. Configure databases['default'] "
                "and its environment overrides before running minix add rag."
            )
        changes = {config_path: _register_modules(source, tree)}
        template = (_TEMPLATES / ".env.example").read_text()
        defaults = template.split("# __BEGIN_RAG__\n", 1)[1].split("# __END_RAG__", 1)[0]
        defaults += "QDRANT_URL=http://localhost:${QDRANT_PORT:-6333}\n"
        defaults += "QDRANT_PORT=6333\nQDRANT_GRPC_PORT=6334\n"
        for name in (".env", ".env.example"):
            path = root / name
            changes[path] = _env_content(path.read_text() if path.exists() else "", defaults)

        dockerfile = root / "Dockerfile"
        if dockerfile.exists():
            source = dockerfile.read_text()
            if _DOCKER_MARKER not in source:
                spec = minix_pip_install_spec({"rag"})
                changes[dockerfile] = source.rstrip() + (
                    f"\n\n{_DOCKER_MARKER}\n"
                    "RUN apt-get update && apt-get install -y --no-install-recommends poppler-utils "
                    "&& rm -rf /var/lib/apt/lists/*\n"
                    f'RUN pip install "{spec}"\n'
                )

        compose = root / "docker-compose.yml"
        override = root / "docker-compose.rag.yml"
        if compose.exists():
            rendered = _compose_override(compose.read_text())
            if override.exists() and override.read_text() != rendered:
                raise ValueError("docker-compose.rag.yml already exists with different content; merge it before enabling RAG.")
            changes[override] = rendered
    except (ValueError, SyntaxError) as exc:
        typer.echo(str(exc), err=True)
        raise typer.Exit(code=1) from exc

    written = []
    for path, content in changes.items():
        if not path.exists() or path.read_text() != content:
            path.write_text(content)
            written.append(path.name)
    typer.echo("Enabled RAG; wrote: " + ", ".join(written) if written else "RAG is already enabled.")
    typer.echo('Install local dependencies: pip install "minix[rag]"')
    typer.echo("Set your model provider API key in .env. Create the RAG SQL tables using your schema/migration workflow.")
    if compose.exists():
        typer.echo("Start services: docker compose -f docker-compose.yml -f docker-compose.rag.yml up --build")
    else:
        typer.echo("Run PostgreSQL and Qdrant; PDF ingestion also requires the poppler system package.")
